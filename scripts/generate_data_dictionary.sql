-- =====================================================================
-- scripts/generate_data_dictionary.sql
-- Writes docs/data-dictionary.md from the live database: every table,
-- column, type, nullability, default, key and CHECK rule comes from the
-- system catalog, and every description from migration 007's comments.
-- So the dictionary always matches the built schema.
--
--   psql "<connection string>" -At -f scripts/generate_data_dictionary.sql \
--        -o docs/data-dictionary.md
-- =====================================================================

WITH tbl AS (
    SELECT c.oid, c.relname,
           obj_description(c.oid, 'pg_class') AS descr,
           ROW_NUMBER() OVER (ORDER BY array_position(ARRAY[
               'category','seller','customer','address','product','product_variant',
               'order_header','order_item','payment','review','seller_payout',
               'variant_audit','app_user']::name[], c.relname), c.relname) AS n,
           c.relrowsecurity
    FROM   pg_class c
    WHERE  c.relnamespace = 'marketplace'::regnamespace AND c.relkind = 'r'
),
col AS (
    SELECT a.attrelid, a.attnum, a.attname,
           format_type(a.atttypid, a.atttypmod) AS typ,
           CASE WHEN a.attnotnull THEN 'NO' ELSE 'yes' END AS nullable,
           CASE WHEN a.attidentity IN ('a','d') THEN 'identity'
                ELSE COALESCE(pg_get_expr(d.adbin, d.adrelid), '') END AS dflt,
           col_description(a.attrelid, a.attnum) AS descr
    FROM   pg_attribute a
    LEFT   JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
    WHERE  a.attrelid IN (SELECT oid FROM tbl) AND a.attnum > 0 AND NOT a.attisdropped
),
keys AS (
    SELECT k.conrelid, u.attnum,
           string_agg(CASE k.contype
                        WHEN 'p' THEN 'PK'
                        WHEN 'u' THEN 'UQ'
                        WHEN 'f' THEN 'FK → ' || r.relname
                      END, ', ' ORDER BY position(k.contype::text IN 'pfu')) AS keyinfo
    FROM   pg_constraint k
    CROSS  JOIN LATERAL unnest(k.conkey) AS u(attnum)
    LEFT   JOIN pg_class r ON r.oid = k.confrelid
    WHERE  k.connamespace = 'marketplace'::regnamespace AND k.contype IN ('p','u','f')
    GROUP  BY k.conrelid, u.attnum
),
rules AS (
    SELECT k.conrelid,
           string_agg('- `' || k.conname || '`: ' ||
                      replace(pg_get_constraintdef(k.oid), '|', '\|'), E'\n'
                      ORDER BY k.contype, k.conname) AS txt
    FROM   pg_constraint k
    WHERE  k.connamespace = 'marketplace'::regnamespace AND k.contype IN ('c','f','u')
    GROUP  BY k.conrelid
),
section AS (
    SELECT t.n,
           '## ' || t.n || '. ' || t.relname || E'\n\n' ||
           COALESCE(t.descr, '') ||
           E'\n\n| Column | Type | Null? | Default | Key | Description |\n|---|---|---|---|---|---|\n' ||
           string_agg('| `' || c.attname || '` | ' || c.typ || ' | ' || c.nullable || ' | ' ||
                      replace(c.dflt, '|', '\|') || ' | ' || COALESCE(k.keyinfo, '') || ' | ' ||
                      COALESCE(c.descr, '') || ' |', E'\n' ORDER BY c.attnum) ||
           COALESCE(E'\n\n**Constraints**\n\n' || r.txt, '') AS md
    FROM   tbl t
    JOIN   col c       ON c.attrelid = t.oid
    LEFT   JOIN keys k ON k.conrelid = t.oid AND k.attnum = c.attnum
    LEFT   JOIN rules r ON r.conrelid = t.oid
    GROUP  BY t.n, t.relname, t.descr, t.relrowsecurity, r.txt
)
SELECT '# Data Dictionary - marketplace schema' || E'\n\n' ||
       'Generated from the built database by `scripts/generate_data_dictionary.sql` ' ||
       '(descriptions come from `migrations/007_comments.sql`). ' ||
       'All money columns are in US dollars; all timestamps are `timestamp with time zone`.' || E'\n\n' ||
       '**Key column:** PK = primary key, UQ = part of a UNIQUE constraint, FK → table = foreign key. ' ||
       '**Default "identity":** the value is generated automatically (`GENERATED BY DEFAULT AS IDENTITY` or `ALWAYS`).' || E'\n\n' ||
       E'## Tables\n\n| # | Table | Description |\n|---|---|---|\n' ||
       (SELECT string_agg('| ' || n || ' | [`' || relname || '`](#' || n || '-' || relname || ') | ' ||
                          COALESCE(descr, '') || ' |', E'\n' ORDER BY n) FROM tbl) ||
       E'\n\n' ||
       (SELECT string_agg(md, E'\n\n' ORDER BY n) FROM section) ||
       E'\n\n## Views\n\n| View | Description |\n|---|---|\n' ||
       (SELECT string_agg('| `' || c.relname || '` | ' || COALESCE(obj_description(c.oid, 'pg_class'), '') || ' |',
                          E'\n' ORDER BY c.relname)
        FROM pg_class c WHERE c.relnamespace = 'marketplace'::regnamespace AND c.relkind = 'v') ||
       E'\n\n## Functions, procedure and trigger\n\n| Object | Kind | Arguments |\n|---|---|---|\n' ||
       (SELECT string_agg('| `' || p.proname || '` | ' ||
                          CASE p.prokind WHEN 'p' THEN 'procedure'
                               ELSE CASE WHEN p.prorettype = 'trigger'::regtype THEN 'trigger function'
                                         ELSE 'function → ' || format_type(p.prorettype, NULL) END END ||
                          ' | ' || COALESCE(NULLIF(pg_get_function_arguments(p.oid), ''), '(none)') || ' |',
                          E'\n' ORDER BY p.proname)
        FROM pg_proc p WHERE p.pronamespace = 'marketplace'::regnamespace) ||
       E'\n| `trg_variant_audit` | trigger on `product_variant` | AFTER UPDATE OF stock_quantity, price_override → trg_fn_variant_audit() |\n' ||
       E'\n## Security\n\n| Role | Purpose | Access |\n|---|---|---|\n' ||
       '| `mp_viewer` | Read-only catalog analyst | SELECT on category, product, product_variant, seller, v_storefront_catalog |' || E'\n' ||
       '| `mp_staff` | Inventory staff | Same SELECT; UPDATE (stock_quantity, price_override) on product_variant; INSERT on variant_audit |' || E'\n' ||
       '| `mp_customer` | Group role for customer logins | SELECT on address and app_user, filtered by RLS to the customer''s own rows |' || E'\n' ||
       '| `cust_pedro`, `cust_aisha` | Example customer logins (customers 1 and 2) | Members of mp_customer |' || E'\n\n' ||
       E'| Policy | Table | Rule |\n|---|---|---|\n' ||
       (SELECT string_agg('| `' || policyname || '` | ' || tablename || ' | ' ||
                          cmd || ' to ' || array_to_string(roles, ', ') || ' USING ' ||
                          regexp_replace(qual, '\s+', ' ', 'g') || ' |', E'\n' ORDER BY tablename)
        FROM pg_policies WHERE schemaname = 'marketplace') || E'\n';
