--   seller_payout                 : what the marketplace paid each seller
--                                   for their items on one order: gross
--                                   sales, commission kept and net paid.
--                                   paid_at stays NULL until it is paid.
--   product_variant.reorder_level : stock level at or below which a
--                                   variant should be reordered.
-- Safe to rerun.
