SET search_path TO marketplace;

ALTER TABLE product_variant
    ADD COLUMN IF NOT EXISTS reorder_level INTEGER NOT NULL DEFAULT 10;

ALTER TABLE product_variant DROP CONSTRAINT IF EXISTS product_variant_reorder_ck;
ALTER TABLE product_variant
    ADD CONSTRAINT product_variant_reorder_ck CHECK (reorder_level >= 0);

CREATE TABLE IF NOT EXISTS seller_payout (
    payout_id     INTEGER GENERATED BY DEFAULT AS IDENTITY,
    seller_id     INTEGER       NOT NULL,
    order_id      INTEGER       NOT NULL,
    gross_amount  NUMERIC(12,2) NOT NULL,
    commission    NUMERIC(12,2) NOT NULL,
    net_amount    NUMERIC(12,2) NOT NULL,
    paid_at       TIMESTAMPTZ,
    CONSTRAINT seller_payout_pk              PRIMARY KEY (payout_id),
    CONSTRAINT seller_payout_seller_order_uq UNIQUE (seller_id, order_id),
    CONSTRAINT seller_payout_amounts_ck
        CHECK (gross_amount >= 0 AND commission >= 0
               AND net_amount = gross_amount - commission),
    -- Rule: payouts are financial records; a seller or an order that has
    -- a payout cannot be deleted.
    CONSTRAINT seller_payout_seller_fk FOREIGN KEY (seller_id)
        REFERENCES seller (seller_id)
        ON DELETE RESTRICT ON UPDATE NO ACTION,
    CONSTRAINT seller_payout_order_fk FOREIGN KEY (order_id)
        REFERENCES order_header (order_id)
        ON DELETE RESTRICT ON UPDATE NO ACTION
);
